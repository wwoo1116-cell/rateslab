'use client';

/**
 * 간격은 **관계**가 정한다 — 요소의 종류가 아니라.
 * [OWNER 2026-09-23 · 폭·간격 정규화 Phase B]
 *
 * ── 09-02 의 「12px 한 값」은 어디까지 참이었나 ─────────────────────────────
 *
 * [OWNER 2026-09-02 — "가로 근접성 리듬 폐기하고 그냥 동간격으로 배치하기"] 는
 * **폼 행의 칸 사이**를 한 값으로 눌렀고, 그건 지금도 옳다(`FIELD` = 12). 다만
 * 그 결정이 덮지 않은 관계가 넷 더 있었고, 그 자리들은 각자 다른 수로 흩어져
 * 있었다 — 앱 전체 `gap` 값이 **아홉 가지**였다(0·0.25·0.5·0.75·1·1.5·2·3·4).
 *
 * 이 파일은 그 아홉을 **관계 다섯**으로 줄인다. 12px 은 그대로 살아 있다.
 *
 * ── ★갭은 «상자»에 걸리는데 눈은 «글자»를 본다 [실측 2026-09-23] ──────────
 *
 * 백테스트 버튼 줄의 상자 틈은 **6·6 으로 균일**한데 글자 틈은 **38 대 22** 였다
 * (「줄 추가 → 실행」 대 「실행 → 캡션」). 버튼은 제 패딩 16 을 좌우로 지고 캡션은
 * 맨 글자라, 한 gap 값이 눈에는 두 값이 된다. 오너가 「간격이 제각각」이라고
 * 한 자리가 정확히 이것이다.
 *
 * 그래서 이 토큰들은 **글자 틈(ink)** 을 목표로 하고, 상자 틈은 거기서 각
 * 요소의 패딩을 빼서 나온다:
 *
 * ```
 *   상자틈 = 목표글자틈 − 왼쪽요소의 오른패딩 − 오른쪽요소의 왼패딩
 * ```
 *
 * ── 버튼 줄의 목표가 38 인 것은 **고른 값이 아니라 바닥**이다 ───────────────
 *
 * CDS 버튼의 패딩이 좌우 16 이라 버튼↔버튼의 글자 틈은 아무리 좁혀도
 * `상자틈 + 32` 다. 상자가 0 이면 두 버튼의 테두리가 맞붙어 한 덩어리로 보이므로
 * 최소한의 보이는 틈 6 이 필요하고, 그래서 **가능한 최소 글자 틈이 38** 이다.
 * 버튼↔캡션은 패딩이 한쪽뿐이라 상자 22 로 같은 38 을 만든다.
 *
 * 더 좁히려면 CDS `Button` 의 패딩을 건드려야 하는데, 그건 앱의 모든 버튼을
 * 바꾸는 일이라 여기서 안 한다 — 대신 그 사실을 적어 둔다.
 */

/** CDS 컨트롤이 제 안에 지고 있는 좌우 패딩(px) — 실측 2026-09-23. */
export const PAD = {
  /** `Button size="xs"` 좌우. 글자 틈 산술의 그 16. */
  button: 16,
  /** 맨 글자(`TextCaption`·`TextLegal`)는 패딩이 없다. */
  text: 0,
} as const;

/**
 * 관계별 **글자 틈** 목표(px).
 *
 * 이름이 요소가 아니라 «무엇과 무엇 사이인가» 인 것이 이 파일의 전부다.
 */
export const INK = {
  /** 칸↔칸 — 09-02 의 그 12px. 컨트롤은 패딩이 폭에 든 상자라 상자틈 = 글자틈. */
  field: 12,
  /** 묶음↔묶음 — 칸 셋을 한 덩어리로 읽히게 하는 틈. 칸 틈의 두 배. */
  group: 24,
  /** 라벨→컨트롤(세로). 2px 이던 자리 — T2(≥4) 미달이었다. */
  label: 4,
  /** 컨트롤·버튼 → 그 옆의 설명 글자. 버튼 줄의 바닥값(위 산술). */
  caption: 38,
  /** 한 칸 **안**에서 붙어 다니는 것들(입력+버튼, 알약 묶음). */
  tight: 4,
} as const;

/**
 * CDS 눈금으로 옮긴 같은 토큰 — **`gap` prop 에 넣을 수 있는 꼴**.
 *
 * `INK` 는 px 로 적는다(사람이 읽고 가드가 재는 단위). CDS `gap` 은 8px 눈금의
 * **리터럴 유니온**이라 계산된 `number` 를 안 받는다. 그래서 같은 수를 두 꼴로
 * 두되, 바로 아래 시험 한 줄이 둘이 안 어긋나게 잡는다
 * (`guards/fit-policy.test.ts`).
 */
export const GAP = {
  /** 12px */ field: 1.5,
  /** 24px */ group: 3,
  /** 4px  */ label: 0.5,
  /** 4px  */ tight: 0.5,
} as const;

/** px ↔ CDS 눈금. 가드가 `GAP` 과 `INK` 의 대사에 쓴다. */
export const unit = (px: number): number => px / 8;

/**
 * 두 요소 사이에 줄 **상자 틈** — 목표 글자 틈에서 서로의 패딩을 뺀다.
 *
 * 음수가 나오면 그 목표는 이 조합에서 불가능하다는 뜻이라 0 으로 깎고, 그때는
 * 글자 틈이 목표보다 넓어진다 — 그 사실을 숨기지 않으려고 함수가 아니라 표로
 * 적는 자리에서만 쓴다.
 */
export const boxGap = (ink: number, leftPad: number, rightPad: number): number =>
  Math.max(0, ink - leftPad - rightPad);

/**
 * 버튼 줄의 **상자 틈** — `INK.caption`(38) 을 두 조합에서 같은 글자 틈으로
 * 만드는 값. 산술은 위 문단이고, 여기 적힌 수는 그 답이다:
 *
 * ```
 * 버튼↔버튼   38 − 16 − 16 =  6px  → 0.75
 * 버튼↔캡션   38 − 16 −  0 = 22px  → 2.75
 * ```
 *
 * 종전에는 둘 다 6px 이었고, 그래서 글자 틈이 38 대 22 로 갈렸다.
 */
export const BUTTON_ROW = {
  /** 6px */ betweenButtons: 0.75,
  /** 22px */ buttonToCaption: 2.75,
} as const;
